def _events(lang):
    eng = lang == "eng"
    out = {}
    for cls, (et, ei), (rt, ri), options, pages in EVENTS:
        eid = PREFIX + _snake(cls)
        out[f"{eid}.title"] = et if eng else rt
        out[f"{eid}.pages.INITIAL.description"] = ei if eng else ri
        opts = dict(options)
        if cls != "CoastRaidersEvent":  # от грабителей не уйти: платить, драться или откупаться
            opts.setdefault("LEAVE", LEAVE)
        for key, (a, b, c, d) in opts.items():
            out[f"{eid}.pages.INITIAL.options.{key}.title"] = a if eng else c
            out[f"{eid}.pages.INITIAL.options.{key}.description"] = b if eng else d
        all_pages = dict(pages)
        if "LEAVE" in opts:
            all_pages.setdefault("LEAVE", LEFT)
        for page, (e, r) in all_pages.items():
            out[f"{eid}.pages.{page}.description"] = e if eng else r
    return out


