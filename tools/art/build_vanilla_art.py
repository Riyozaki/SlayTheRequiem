#!/usr/bin/env python3
"""Таблица заимствованного арта: tools/art/vanilla_art.csv → mod/SlayTheRequiemCode/Art/VanillaArtTable.g.cs.

Политика (docs/plan/art-ui-animation-spec.md §0): у модели мода картинка ищется так —
свой файл в mod/SlayTheRequiem/images → ванильный портрет/значок из этой таблицы → заглушка шаблона.
Своё рисуется только для ключевого (герои, UI-значки ◆ ✦ ⚖, ключевые карты); всё остальное — ванильный арт.

Что делает:
  * разворачивает шаблоны (Node*, *Essence) по именам классов моделей мода;
  * проверяет, что ванильные имена есть в снимке игры (tools/art/vanilla_models.txt, см. snapshot_vanilla.py);
  * пишет C#-таблицу (id ванильных моделей уже в нижнем регистре, как в путях атласов игры);
  * печатает покрытие и модели без арта.

Запуск:
    python3 tools/art/build_vanilla_art.py           # пересобрать таблицу
    python3 tools/art/build_vanilla_art.py --check   # CI: код 1, если таблица устарела, есть ошибки или пробелы
"""
from __future__ import annotations

import argparse
import csv
import fnmatch
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
CSV_PATH = os.path.join(HERE, "vanilla_art.csv")
SNAPSHOT = os.path.join(HERE, "vanilla_models.txt")
OUT = os.path.join(ROOT, "mod", "SlayTheRequiemCode", "Art", "VanillaArtTable.g.cs")

sys.path.insert(0, os.path.join(ROOT, "tools", "assets"))
import asset_manifest  # noqa: E402

KINDS = {"card": "CardTable", "power": "PowerTable", "relic": "RelicTable", "event": "EventTable", "enchantment": "EnchantmentTable"}


def game_slug(name: str) -> str:
    """Порт StringHelper.Slugify игры (id модели = Slugify(имя класса)), в нижнем регистре — как в путях картинок."""
    text = re.sub(r"([A-Za-z0-9])(?=[A-Z])", r"\1_", name.strip())
    text = re.sub(r"\s+", "_", text.upper())
    return re.sub(r"[^A-Z0-9_]", "", text).lower()


def mod_models() -> dict[str, list[str]]:
    classes = asset_manifest.load_classes()
    out: dict[str, list[str]] = {k: [] for k in KINDS}
    for name, info in sorted(classes.items()):
        if info["abstract"] or not info["sealed"]:
            continue
        base = asset_manifest.kind_of(info["base"], classes)
        if base is None:
            continue
        kind = asset_manifest.BASES[base][0]
        if kind in out:
            out[kind].append(name)
    return out


def vanilla_models() -> dict[str, dict[str, str]]:
    """kind → {Класс: путь-ключ}; у карт ключ «пул/Класс»."""
    known: dict[str, dict[str, str]] = {k: {} for k in KINDS}
    for line in open(SNAPSHOT, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        kind, pool, name = line.split()
        key = f"{pool}/{name}" if kind == "card" else name
        known[kind][key] = key
    return known


def read_rules():
    rules = []
    with open(CSV_PATH, encoding="utf-8") as fh:
        lines = [ln for ln in fh if ln.strip() and not ln.lstrip().startswith("#")]
    for n, row in enumerate(csv.DictReader(lines), start=2):
        rules.append((row["kind"].strip(), row["mod"].strip(), row["vanilla"].strip(), n))
    return rules


def resolve(models, known, rules, errors):
    """Сначала шаблоны (первый подошедший), затем точные имена поверх — точное имя всегда важнее шаблона."""
    table: dict[str, dict[str, str]] = {k: {} for k in KINDS}
    exact = []
    for kind, pattern, vanilla, _ in rules:
        if kind not in KINDS:
            errors.append(f"vanilla_art.csv: неизвестный вид «{kind}» ({pattern})")
            continue
        if vanilla not in known[kind]:
            errors.append(f"vanilla_art.csv: {kind} {pattern} → нет ванильной модели «{vanilla}» в {os.path.basename(SNAPSHOT)}")
            continue
        if not any(ch in pattern for ch in "*?["):
            if pattern not in models[kind]:
                errors.append(f"vanilla_art.csv: {kind} «{pattern}» — нет такой модели в моде")
            else:
                exact.append((kind, pattern, vanilla))
            continue
        matched = [m for m in models[kind] if fnmatch.fnmatchcase(m, pattern)]
        if not matched:
            errors.append(f"vanilla_art.csv: {kind} «{pattern}» не совпал ни с одной моделью мода")
        for m in matched:
            table[kind].setdefault(m, vanilla)
    for kind, mod, vanilla in exact:
        table[kind][mod] = vanilla
    return table


def vanilla_key(kind: str, vanilla: str) -> str:
    if kind == "card":
        pool, name = vanilla.split("/")
        return f"{pool}/{game_slug(name)}"
    return game_slug(vanilla)


def render(table) -> str:
    out = [
        "// <auto-generated>",
        "// tools/art/build_vanilla_art.py из tools/art/vanilla_art.csv — руками не править.",
        "// Ключ — имя класса модели мода, значение — id ванильной модели (у карт «пул/id»), как в путях атласов игры.",
        "// </auto-generated>",
        "",
        "namespace SlayTheRequiem.SlayTheRequiemCode.Art;",
        "",
        "public static partial class VanillaArt",
        "{",
    ]
    for kind, prop in KINDS.items():
        out.append(f"    private static readonly Dictionary<string, string> {prop} = new()")
        out.append("    {")
        for mod, vanilla in sorted(table[kind].items()):
            out.append(f'        ["{mod}"] = "{vanilla_key(kind, vanilla)}",')
        out.append("    };")
        out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="не писать файл; код 1 при устаревшей таблице, ошибках или пробелах")
    args = ap.parse_args()

    models, known, rules = mod_models(), vanilla_models(), read_rules()
    errors: list[str] = []
    table = resolve(models, known, rules, errors)
    missing = {k: [m for m in models[k] if m not in table[k]] for k in KINDS}

    for kind in KINDS:
        n, total = len(table[kind]), len(models[kind])
        print(f"{kind:12} {n:4}/{total:<4} с ванильным артом" + (f"; без арта: {', '.join(missing[kind])}" if missing[kind] else ""))
    text = render(table)
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            errors.append(f"{os.path.relpath(OUT, ROOT)} устарел — запустите python3 tools/art/build_vanilla_art.py")
        errors += [f"{k}: {m} — нет строки в vanilla_art.csv" for k in KINDS for m in missing[k]]
    else:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"→ {os.path.relpath(OUT, ROOT)}")
    for e in errors:
        print("✗", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
